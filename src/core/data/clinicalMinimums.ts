/**
 * Поиск клинического минимума по коду МКБ.
 * Ищет точное совпадение, потом по первым 3 символам, потом по первым 2.
 */
export function findClinicalMinimum(icdCode: string): ClinicalMinimum | null {
  if (!icdCode) return null;
  
  // Точное совпадение
  if (CLINICAL_MINIMUMS[icdCode]) return CLINICAL_MINIMUMS[icdCode];
  
  // По первым 3 символам
  const prefix3 = icdCode.substring(0, 3);
  if (CLINICAL_MINIMUMS[prefix3]) return CLINICAL_MINIMUMS[prefix3];
  
  // По первым 2 символам (для M15-M19 → M15)
  const prefix2 = icdCode.substring(0, 2);
  // Ищем ключ, начинающийся с prefix2
  for (const key of Object.keys(CLINICAL_MINIMUMS)) {
    if (key.startsWith(prefix2)) return CLINICAL_MINIMUMS[key];
  }
  
  return null;
}